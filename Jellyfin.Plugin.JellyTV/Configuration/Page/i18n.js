  // Traduce un nodo y todo lo que cuelga de él (texto, placeholder, label, title y los párrafos marcados con data-i18n).
  function jtWalk(n){
      if(n.nodeType === 3){
          var parent = n.parentNode && n.parentNode.nodeName;
          if(parent === 'SCRIPT' || parent === 'STYLE' || parent === 'TEXTAREA'){ return; }
          var raw = n.nodeValue, key = jtNorm(raw);
          if(!key){ return; }
          var en = jtLookup(key);
          if(en !== null){
              var next = /^\s*/.exec(raw)[0] + en + /\s*$/.exec(raw)[0];
              if(next !== raw){ n.nodeValue = next; }
          }
          return;
      }
      if(n.nodeType !== 1 || n.nodeName === 'SCRIPT' || n.nodeName === 'STYLE'){ return; }
      var id = n.getAttribute('data-i18n');
      if(id){
          if(Object.prototype.hasOwnProperty.call(JT_EN_HTML, id) && !n.hasAttribute('data-i18n-done')){
              n.setAttribute('data-i18n-done', '1');
              n.innerHTML = JT_EN_HTML[id];
          }
          return;
      }
      for(var i = 0; i < JT_ATTRS.length; i++){
          var v = n.getAttribute(JT_ATTRS[i]);
          if(v){ var tr = jtLookup(jtNorm(v)); if(tr !== null && tr !== v){ n.setAttribute(JT_ATTRS[i], tr); } }
      }
      for(var c = n.firstChild; c; c = c.nextSibling){ jtWalk(c); }
  }
